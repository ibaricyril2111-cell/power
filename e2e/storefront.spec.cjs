const { test, expect } = require('@playwright/test')
async function dismissCookies(page) {
  const cookies = page.getByRole('button', { name: 'Essentiels uniquement', exact: true })
  await cookies.waitFor({state:'visible',timeout:10000})
  await cookies.click()
  await expect(cookies).toHaveCount(0)
}
async function home(page) {
  await page.goto('/')
  await dismissCookies(page)
  await expect(page.getByRole('heading', { name: 'Tout le marché POWER', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: /^Ajouter .+ au panier$/ }).first()).toBeEnabled()
}
test('catalogue, prix et boutons restent dans la largeur disponible', async ({ page }) => {
  await home(page)
  await expect(page.getByRole('region', { name: 'À la une', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  const overflows = await page.locator('button').evaluateAll(elements => elements.filter(el => {
    const box = el.getBoundingClientRect()
    return box.width > 0 && box.height > 0 && (el.scrollWidth > el.clientWidth + 2 || el.scrollHeight > el.clientHeight + 2)
  }).map(el => el.textContent.trim()).slice(0, 8))
  expect(overflows).toEqual([])
  const prices = page.locator('[data-product-price]')
  expect(await prices.count()).toBeGreaterThan(0)
  expect(await prices.evaluateAll(elements => elements.every(el => getComputedStyle(el).position !== 'absolute'))).toBe(true)
  const filters = page.getByLabel('Filtrer les produits par catégorie')
  await filters.getByRole('button', { name: 'Légumes', exact: true }).click()
  await expect(filters.getByRole('button', { name: 'Légumes', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('region', { name: 'Aromates', exact: true })).toHaveCount(0)
  await filters.getByRole('button', { name: 'Tout', exact: true }).click()
  await page.getByRole('textbox', { name: 'Rechercher dans les produits' }).fill('Basilic')
  await expect(page.getByRole('heading', { name: 'Basilic Frais', exact: true }).first()).toBeVisible()
  await page.getByRole('textbox', { name: 'Rechercher dans les produits' }).fill('zzzz-inexistant')
  await expect(page.getByText('Aucun produit trouvé.')).toBeVisible()
})
test('fiche produit et panier fonctionnent depuis le frontend', async ({ page }) => {
  await home(page)
  await page.getByRole('textbox', { name: 'Rechercher dans les produits' }).fill('Basilic')
  await page.getByRole('button', { name: 'Voir le détail de Basilic Frais', exact: true }).filter({ visible: true }).click()
  await expect(page.getByRole('dialog').first()).toBeVisible()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: 'Ajouter Basilic Frais au panier', exact: true }).filter({ visible: true }).click()
  await expect(page.getByRole('banner').getByRole('button', { name: 'Panier', exact: true })).toContainText('1', {timeout:20000})
  await page.getByRole('banner').getByRole('button', { name: 'Panier', exact: true }).click()
  const cart = page.getByRole('dialog', { name: 'Mon Panier' })
  await expect(cart.getByText('Basilic Frais', { exact: true })).toBeVisible({timeout:20000})
  await expect(cart.getByText('Total TTC', { exact: true })).toBeVisible()
  // No checkout submission: these checks never create an order or consume stock.
})
test('inscription compacte : avatar en modale, téléphone, compte et validation', async ({ page }) => {
  await page.goto('/connexion')
  await dismissCookies(page)
  await page.getByRole('button', { name: 'Créer un compte', exact: true }).click()
  await expect(page.getByLabel('Téléphone', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Type de compte', { exact: true })).toBeVisible()
  await expect(page.getByLabel('Facturation', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Choisir Fraise', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: /Choisir mon avatar/ }).click()
  const dialog = page.getByRole('dialog', { name: 'Mon avatar POWER' })
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: 'Choisir Fraise', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('button', { name: /Avatar : Fraise/ })).toBeVisible()
  await page.getByLabel('Type de compte', { exact: true }).selectOption('professionnel')
  await expect(page.getByLabel('Type de compte', { exact: true })).toHaveValue('professionnel')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})
test('les vrais créneaux de livraison et retrait se sélectionnent', async ({ page }) => {
  await page.goto('/livraison')
  await dismissCookies(page)
  const planner = page.getByRole('region', { name: 'Créneaux disponibles', exact: true })
  await expect(planner).toBeVisible()
  for (const mode of ['Livraison', 'Retrait en magasin']) {
    await planner.getByRole('button', { name: mode, exact: true }).click()
    const slot = planner.getByRole('button', { name: /09:00 - 10:00/ }).first()
    await expect(slot).toBeEnabled({timeout:20000})
    await slot.click()
    await expect(slot).toHaveAttribute('aria-pressed','true')
    const next = planner.getByRole('link', { name:'Continuer avec ce créneau', exact:true })
    await expect(next).toBeVisible()
    await expect(next).toHaveAttribute('href',new RegExp('mode='+(mode==='Livraison'?'livraison':'retrait')))
  }
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
})
